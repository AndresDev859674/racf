use std::fmt::Write as _;

use base64::Engine as _;
use racf_core::{Channel, Metadata, SampleEncoding};

/// Description of one clip to embed.
pub struct ClipSpec<'a> {
    pub id: &'a str,
    pub at_ms: u64,
    pub gain: f32,
    pub pan: f32,
    pub channel: Option<Channel>,
    pub sample_rate: u32,
    pub channels: u8,
    pub encoding: SampleEncoding,
    pub data: &'a [u8],
}

/// Renders a complete, readable RACF document around an embedded audio clip.
pub fn render_document(metadata: &Metadata, clip: &ClipSpec<'_>) -> String {
    let mut output = String::new();
    let frame_bytes = clip.channels as usize * clip.encoding.bytes_per_sample();
    let frames = clip.data.len().checked_div(frame_bytes).unwrap_or(0);
    let duration_secs = if clip.sample_rate == 0 {
        0.0
    } else {
        frames as f32 / clip.sample_rate as f32
    };

    output.push_str("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
    output.push_str("<!-- Generated by racf-utils. Audio is embedded, not linked. -->\n");
    output.push_str("<racf version=\"1.0\" channelLayout=\"stereo\">\n");

    if !metadata.is_empty() {
        output.push_str("    <metadata>\n");
        write_field(&mut output, "title", metadata.title.as_deref());
        write_field(&mut output, "description", metadata.description.as_deref());
        write_field(&mut output, "artist", metadata.artist.as_deref());
        write_field(&mut output, "album", metadata.album.as_deref());
        output.push_str("    </metadata>\n");
    }

    output.push_str("    <audio>\n");
    write!(
        output,
        "        <clip id=\"{}\" at=\"{}ms\" gain=\"{:.3}\" pan=\"{:.3}\"",
        escape_attribute(clip.id),
        clip.at_ms,
        clip.gain,
        clip.pan
    )
    .unwrap();

    if let Some(channel) = clip.channel {
        write!(output, " channel=\"{channel}\"").unwrap();
    }

    writeln!(
        output,
        " sampleRate=\"{}\" channels=\"{}\" encoding=\"{}\" duration=\"{:.3}s\">",
        clip.sample_rate, clip.channels, clip.encoding, duration_secs
    )
    .unwrap();

    let encoded = base64::engine::general_purpose::STANDARD.encode(clip.data);
    output.push_str("            <data>\n");
    for line in encoded.as_bytes().chunks(96) {
        output.push_str("                ");
        output.push_str(std::str::from_utf8(line).unwrap_or_default());
        output.push('\n');
    }
    output.push_str("            </data>\n");
    output.push_str("        </clip>\n");
    output.push_str("    </audio>\n");
    output.push_str("</racf>\n");

    output
}

fn write_field(output: &mut String, name: &str, value: Option<&str>) {
    if let Some(value) = value {
        writeln!(output, "        <{name}>{}</{name}>", escape_text(value)).unwrap();
    }
}

fn escape_text(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

fn escape_attribute(value: &str) -> String {
    escape_text(value)
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

#[cfg(test)]
mod tests {
    use super::*;
    use racf_core::parse_document;

    #[test]
    fn rendered_document_parses_and_preserves_metadata() {
        let metadata = Metadata {
            title: Some("A & B".to_string()),
            description: Some("A < B".to_string()),
            artist: Some("Artist".to_string()),
            album: Some("Album".to_string()),
        };
        let data = vec![0xffu8; 441];
        let clip = ClipSpec {
            id: "main",
            at_ms: 0,
            gain: 1.0,
            pan: 0.0,
            channel: None,
            sample_rate: 44_100,
            channels: 1,
            encoding: SampleEncoding::Mulaw,
            data: &data,
        };

        let xml = render_document(&metadata, &clip);
        let document = parse_document(&xml).unwrap();

        assert_eq!(document.metadata.title.as_deref(), Some("A & B"));
        assert_eq!(document.metadata.description.as_deref(), Some("A < B"));
        assert_eq!(document.audio_clips.len(), 1);
        assert_eq!(document.audio_clips[0].data, data);
        assert!((document.audio_clips[0].duration_secs() - 0.01).abs() < 0.0001);
    }
}
